export function findBembaWord(query: string): BembaEntry | undefined {
  const normalized = query.trim().toLowerCase();

  if (!normalized) {
    return undefined;
  }

  return bembaDictionary.find(
    (entry) =>
      entry.english.toLowerCase() === normalized ||
      entry.bemba.toLowerCase() === normalized
  );
}

export function searchBembaDictionary(query: string): BembaEntry[] {
  const normalized = query.trim().toLowerCase();

  if (!normalized) {
    return bembaDictionary;
  }

  return bembaDictionary.filter(
    (entry) =>
      entry.english.toLowerCase().includes(normalized) ||
      entry.bemba.toLowerCase().includes(normalized)
  );
}
